export function getTopicById(id: string): SyllabusTopic | undefined {
  return syllabusTopics.find((t) => t.id === id);
}

export function getTopicByNumber(n: number): SyllabusTopic | undefined {
  return syllabusTopics.find((t) => t.number === n);
}

/** All subtopics flattened, with their owning topic id. */
export function allSubtopics() {
  return syllabusTopics.flatMap((t) =>
    t.subtopics.map((s) => ({ ...s, topicId: t.id, topicNumber: t.number })),
  );
}
